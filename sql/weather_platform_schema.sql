-- Weather platform metadata schema.
-- Prerequisite: a database administrator must install PostGIS:
-- CREATE EXTENSION IF NOT EXISTS postgis;
-- Then grant the application role schema/table privileges using least privilege.

CREATE SCHEMA IF NOT EXISTS weather;

CREATE TABLE IF NOT EXISTS weather.model (
    model_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    provider TEXT NOT NULL,
    description TEXT,
    nominal_resolution_km NUMERIC(10,3),
    is_ensemble BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weather.forecast_run (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id BIGINT NOT NULL REFERENCES weather.model(model_id),
    run_time TIMESTAMPTZ NOT NULL,
    source_cycle TEXT NOT NULL,
    source_status TEXT NOT NULL DEFAULT 'available',
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(model_id, run_time)
);
CREATE INDEX IF NOT EXISTS forecast_run_time_idx
    ON weather.forecast_run(model_id, run_time DESC);

CREATE TABLE IF NOT EXISTS weather.grid (
    grid_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grid_hash CHAR(64) NOT NULL UNIQUE,
    grid_type TEXT NOT NULL,
    nx INTEGER NOT NULL CHECK (nx > 0),
    ny INTEGER NOT NULL CHECK (ny > 0),
    resolution_x NUMERIC(14,8),
    resolution_y NUMERIC(14,8),
    crs TEXT NOT NULL DEFAULT 'EPSG:4326',
    west DOUBLE PRECISION,
    south DOUBLE PRECISION,
    east DOUBLE PRECISION,
    north DOUBLE PRECISION,
    footprint geometry(MultiPolygon, 4326),
    coordinates_uri TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS grid_footprint_gix ON weather.grid USING GIST(footprint);

CREATE TABLE IF NOT EXISTS weather.variable (
    variable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    description TEXT,
    canonical_unit TEXT NOT NULL,
    standard_name TEXT,
    quantity_kind TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weather.level (
    level_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_of_level TEXT NOT NULL,
    level_value NUMERIC(16,5) NOT NULL,
    level_unit TEXT NOT NULL,
    display_name TEXT,
    UNIQUE(type_of_level, level_value, level_unit)
);

CREATE TABLE IF NOT EXISTS weather.asset (
    asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_uri TEXT NOT NULL UNIQUE,
    asset_format TEXT NOT NULL,
    byte_size BIGINT NOT NULL CHECK (byte_size >= 0),
    sha256 CHAR(64) NOT NULL,
    source_uri TEXT,
    etag TEXT,
    last_modified TEXT,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS asset_sha256_idx ON weather.asset(sha256);

CREATE TABLE IF NOT EXISTS weather.field (
    field_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES weather.forecast_run(run_id) ON DELETE CASCADE,
    variable_id BIGINT NOT NULL REFERENCES weather.variable(variable_id),
    level_id BIGINT NOT NULL REFERENCES weather.level(level_id),
    grid_id BIGINT NOT NULL REFERENCES weather.grid(grid_id),
    forecast_hour INTEGER NOT NULL CHECK (forecast_hour >= 0),
    valid_time TIMESTAMPTZ NOT NULL,
    source_unit TEXT NOT NULL,
    display_unit TEXT NOT NULL,
    asset_id BIGINT NOT NULL REFERENCES weather.asset(asset_id),
    data_group TEXT,
    member_code TEXT,
    value_min DOUBLE PRECISION,
    value_max DOUBLE PRECISION,
    valid_cell_count BIGINT,
    quality_status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(run_id, variable_id, level_id, grid_id, forecast_hour, member_code, data_group)
);
CREATE INDEX IF NOT EXISTS field_lookup_idx
    ON weather.field(variable_id, level_id, valid_time, forecast_hour);
CREATE INDEX IF NOT EXISTS field_run_idx ON weather.field(run_id);

CREATE TABLE IF NOT EXISTS weather.tile_cache (
    tile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id BIGINT NOT NULL REFERENCES weather.field(field_id) ON DELETE CASCADE,
    z SMALLINT NOT NULL CHECK (z BETWEEN 0 AND 24),
    x INTEGER NOT NULL CHECK (x >= 0),
    y INTEGER NOT NULL CHECK (y >= 0),
    tile_uri TEXT NOT NULL,
    content_type TEXT NOT NULL,
    sha256 CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(field_id, z, x, y)
);
CREATE INDEX IF NOT EXISTS tile_field_idx ON weather.tile_cache(field_id);

CREATE TABLE IF NOT EXISTS weather.ingestion_job (
    job_id UUID PRIMARY KEY,
    source_code TEXT NOT NULL,
    model_code TEXT,
    request_json JSONB NOT NULL,
    source_uri TEXT,
    temporary_uri TEXT,
    final_asset_uri TEXT,
    etag TEXT,
    last_modified TEXT,
    bytes_received BIGINT NOT NULL DEFAULT 0 CHECK (bytes_received >= 0),
    expected_bytes BIGINT CHECK (expected_bytes IS NULL OR expected_bytes >= 0),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    status TEXT NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued','downloading','paused','retrying','validating','processing','complete','failed','cancelled')),
    last_error TEXT,
    started_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ingestion_status_idx ON weather.ingestion_job(status, updated_at);
